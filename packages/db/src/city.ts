import { generateCity, type CityNetwork, type NetworkLink, type Point, type SignalPlan, type Zone } from '@madar/sim-engine';
import { eq, sql } from 'drizzle-orm';
import type { Database } from './client.js';
import { lineWkt, pointWkt, polygonWkt } from './geometry.js';
import * as s from './schema.js';

/** Bidirectional maps between engine codes and database UUIDs for one city. */
export interface CityIdMaps {
  roadIdByCode: Map<string, string>;
  roadCodeById: Map<string, string>;
  nodeIdByCode: Map<string, string>;
  nodeCodeById: Map<string, string>;
}

const CHUNK = 500;
async function insertChunks<T>(rows: T[], insert: (chunk: T[]) => Promise<unknown>): Promise<void> {
  for (let i = 0; i < rows.length; i += CHUNK) await insert(rows.slice(i, i + CHUNK));
}

/**
 * Writes a generated city into the relational/spatial model. Idempotent: an
 * existing city with the same id and version is left untouched.
 */
export async function seedCity(db: Database, network: CityNetwork = generateCity()): Promise<{ created: boolean }> {
  const existing = await db.select().from(s.cities).where(eq(s.cities.id, network.id));
  if (existing[0]?.version === network.version) return { created: false };

  await db.transaction(async (tx) => {
    if (existing.length) await tx.delete(s.cities).where(eq(s.cities.id, network.id));
    await tx.insert(s.cities).values({
      id: network.id,
      name: network.name,
      version: network.version,
      baseDemandVehPerHour: network.baseDemandVehPerHour,
      description: 'Synthetic reference city generated by the MADAR engine. All data is fictional.',
      isSynthetic: true,
    });

    const districtRows = await tx
      .insert(s.districts)
      .values(
        network.districts.map((d) => ({
          cityId: network.id,
          code: d.id,
          name: d.name,
          nameAr: d.nameAr,
          character: d.character,
          color: d.color,
          boundary: polygonWkt(d.boundary),
        })),
      )
      .returning({ id: s.districts.id, code: s.districts.code });
    const districtId = new Map(districtRows.map((r) => [r.code, r.id]));

    const nodeRows = await tx
      .insert(s.intersections)
      .values(
        network.nodes.map((n) => ({
          cityId: network.id,
          code: n.id,
          name: n.name,
          kind: n.kind,
          districtId: n.districtId ? (districtId.get(n.districtId) ?? null) : null,
          geom: pointWkt(n),
        })),
      )
      .returning({ id: s.intersections.id, code: s.intersections.code });
    const nodeId = new Map(nodeRows.map((r) => [r.code, r.id]));
    const nodePos = new Map(network.nodes.map((n) => [n.id, n as Point]));

    const roadIds = new Map<string, string>();
    await insertChunks(network.links, async (chunk: NetworkLink[]) => {
      const rows = await tx
        .insert(s.roads)
        .values(
          chunk.map((l) => ({
            cityId: network.id,
            code: l.id,
            name: l.name,
            fromIntersectionId: nodeId.get(l.from) as string,
            toIntersectionId: nodeId.get(l.to) as string,
            lengthM: l.length,
            lanes: l.lanes,
            speedLimitMs: l.speedLimit,
            saturationFlow: l.saturationFlow,
            roadClass: l.roadClass,
            geom: lineWkt([nodePos.get(l.from) as Point, ...(l.shape ?? []), nodePos.get(l.to) as Point]),
          })),
        )
        .returning({ id: s.roads.id, code: s.roads.code });
      rows.forEach((r) => roadIds.set(r.code, r.id));
    });

    for (const plan of network.signals) {
      const [sig] = await tx
        .insert(s.trafficSignals)
        .values({ intersectionId: nodeId.get(plan.nodeId) as string, offsetS: plan.offset })
        .returning({ id: s.trafficSignals.id });
      await tx.insert(s.signalPhases).values(
        plan.phases.map((p, i) => ({
          signalId: sig!.id,
          phaseIndex: i,
          name: p.name,
          greenS: p.green,
          yellowS: p.yellow,
          allRedS: p.allRed,
          approachRoadIds: p.approaches.map((a) => roadIds.get(a) as string),
        })),
      );
    }

    await insertChunks(network.buildings, (chunk) =>
      tx.insert(s.buildings).values(
        chunk.map((b) => ({
          cityId: network.id,
          code: b.id,
          name: b.name,
          districtId: districtId.get(b.districtId) as string,
          use: b.use,
          heightM: b.height,
          floors: b.floors,
          floorAreaM2: b.floorArea,
          footprint: polygonWkt(b.footprint),
        })),
      ),
    );

    await tx.insert(s.demandZones).values(
      network.zones.map((z) => ({
        cityId: network.id,
        code: z.id,
        name: z.name,
        production: z.production,
        attraction: z.attraction,
        intersectionIds: z.nodes.map((n) => nodeId.get(n) as string),
      })),
    );
  });
  return { created: true };
}

/**
 * Rebuilds the engine's CityNetwork from the database — the worker always
 * simulates what is stored, never an in-memory copy.
 */
export async function loadCityNetwork(db: Database, cityId: string): Promise<{ network: CityNetwork; maps: CityIdMaps }> {
  const [city] = await db.select().from(s.cities).where(eq(s.cities.id, cityId));
  if (!city) throw new Error(`City ${cityId} not found`);

  const districtRows = await db
    .select({
      id: s.districts.id,
      code: s.districts.code,
      name: s.districts.name,
      nameAr: s.districts.nameAr,
      character: s.districts.character,
      color: s.districts.color,
      boundary: sql<string>`ST_AsGeoJSON(${s.districts.boundary})`,
    })
    .from(s.districts)
    .where(eq(s.districts.cityId, cityId))
    .orderBy(s.districts.code);
  const districtCode = new Map(districtRows.map((d) => [d.id, d.code]));

  const nodeRows = await db
    .select({
      id: s.intersections.id,
      code: s.intersections.code,
      name: s.intersections.name,
      kind: s.intersections.kind,
      districtId: s.intersections.districtId,
      x: sql<number>`ST_X(${s.intersections.geom})`,
      y: sql<number>`ST_Y(${s.intersections.geom})`,
    })
    .from(s.intersections)
    .where(eq(s.intersections.cityId, cityId))
    .orderBy(s.intersections.code);

  const roadRows = await db
    .select({
      id: s.roads.id,
      code: s.roads.code,
      name: s.roads.name,
      from: s.roads.fromIntersectionId,
      to: s.roads.toIntersectionId,
      lengthM: s.roads.lengthM,
      lanes: s.roads.lanes,
      speed: s.roads.speedLimitMs,
      sat: s.roads.saturationFlow,
      roadClass: s.roads.roadClass,
      geom: sql<string>`ST_AsGeoJSON(${s.roads.geom})`,
    })
    .from(s.roads)
    .where(eq(s.roads.cityId, cityId))
    .orderBy(s.roads.code);

  const maps: CityIdMaps = {
    roadIdByCode: new Map(roadRows.map((r) => [r.code, r.id])),
    roadCodeById: new Map(roadRows.map((r) => [r.id, r.code])),
    nodeIdByCode: new Map(nodeRows.map((n) => [n.code, n.id])),
    nodeCodeById: new Map(nodeRows.map((n) => [n.id, n.code])),
  };

  const phaseRows = await db
    .select({
      intersectionId: s.trafficSignals.intersectionId,
      offset: s.trafficSignals.offsetS,
      phaseIndex: s.signalPhases.phaseIndex,
      name: s.signalPhases.name,
      green: s.signalPhases.greenS,
      yellow: s.signalPhases.yellowS,
      allRed: s.signalPhases.allRedS,
      approaches: s.signalPhases.approachRoadIds,
    })
    .from(s.signalPhases)
    .innerJoin(s.trafficSignals, eq(s.signalPhases.signalId, s.trafficSignals.id))
    .innerJoin(s.intersections, eq(s.trafficSignals.intersectionId, s.intersections.id))
    .where(eq(s.intersections.cityId, cityId))
    .orderBy(s.intersections.code, s.signalPhases.phaseIndex);

  const signals = new Map<string, SignalPlan>();
  for (const p of phaseRows) {
    const code = maps.nodeCodeById.get(p.intersectionId) as string;
    const plan = signals.get(code) ?? { nodeId: code, offset: p.offset, phases: [] };
    plan.phases.push({
      name: p.name,
      green: p.green,
      yellow: p.yellow,
      allRed: p.allRed,
      approaches: p.approaches.map((id) => maps.roadCodeById.get(id) as string),
    });
    signals.set(code, plan);
  }

  const buildingRows = await db
    .select({
      code: s.buildings.code,
      name: s.buildings.name,
      districtId: s.buildings.districtId,
      use: s.buildings.use,
      height: s.buildings.heightM,
      floors: s.buildings.floors,
      floorArea: s.buildings.floorAreaM2,
      footprint: sql<string>`ST_AsGeoJSON(${s.buildings.footprint})`,
    })
    .from(s.buildings)
    .where(eq(s.buildings.cityId, cityId))
    .orderBy(s.buildings.code);

  const zoneRows = await db.select().from(s.demandZones).where(eq(s.demandZones.cityId, cityId)).orderBy(s.demandZones.code);

  const ring = (geojson: string): Point[] => {
    const coords = (JSON.parse(geojson) as { coordinates: number[][][] }).coordinates[0] ?? [];
    return coords.slice(0, -1).map(([x, y]) => ({ x: x as number, y: y as number }));
  };

  const network: CityNetwork = {
    id: city.id,
    name: city.name,
    version: city.version,
    baseDemandVehPerHour: city.baseDemandVehPerHour,
    nodes: nodeRows.map((n) => ({
      id: n.code,
      name: n.name,
      kind: n.kind,
      x: Number(n.x),
      y: Number(n.y),
      districtId: n.districtId ? (districtCode.get(n.districtId) ?? null) : null,
    })),
    links: roadRows.map((r) => {
      const coords = (JSON.parse(r.geom) as { coordinates: number[][] }).coordinates;
      const inner = coords.slice(1, -1).map(([x, y]) => ({ x: x as number, y: y as number }));
      return {
        id: r.code,
        name: r.name,
        from: maps.nodeCodeById.get(r.from) as string,
        to: maps.nodeCodeById.get(r.to) as string,
        length: r.lengthM,
        lanes: r.lanes,
        speedLimit: r.speed,
        saturationFlow: r.sat,
        roadClass: r.roadClass,
        ...(inner.length ? { shape: inner } : {}),
      };
    }),
    signals: [...signals.values()],
    districts: districtRows.map((d) => ({
      id: d.code,
      name: d.name,
      nameAr: d.nameAr,
      character: d.character,
      color: d.color,
      boundary: ring(d.boundary),
    })),
    buildings: buildingRows.map((b) => ({
      id: b.code,
      name: b.name,
      districtId: districtCode.get(b.districtId) as string,
      use: b.use,
      height: b.height,
      floors: b.floors,
      floorArea: b.floorArea,
      footprint: ring(b.footprint),
    })),
    zones: zoneRows.map(
      (z): Zone => ({
        id: z.code,
        name: z.name,
        production: z.production,
        attraction: z.attraction,
        nodes: z.intersectionIds.map((id) => maps.nodeCodeById.get(id) as string),
      }),
    ),
  };
  // Sort by code in JS (byte order) so iteration order — and therefore results —
  // never depends on the database's collation settings.
  const byId = <T extends { id: string }>(xs: T[]) => xs.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  byId(network.nodes);
  byId(network.links);
  byId(network.districts);
  byId(network.buildings);
  byId(network.zones);
  network.signals.sort((a, b) => (a.nodeId < b.nodeId ? -1 : 1));
  for (const plan of network.signals) for (const p of plan.phases) p.approaches.sort();
  return { network, maps };
}
